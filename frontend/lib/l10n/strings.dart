class Strings {
  const Strings(this.locale);
  final Locale locale;

  String call(String key) {
    final pair = _messages[key];
    assert(pair != null, 'Missing translation: $key');
    return pair?[locale.languageCode == 'en' ? 1 : 0] ?? key;
  }
}

